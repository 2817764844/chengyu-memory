#!/usr/bin/env node
/**
 * Build chengyu-bank.js and chengyu-similar.js from idiom-clusters.json.
 * Run: node tools/build-bank.js
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const clusters = JSON.parse(
  fs.readFileSync(path.join(root, "data", "idiom-clusters.json"), "utf8")
);

const bank = [];
const similar = {};
const byCluster = {};

for (const group of clusters) {
  const texts = group.items.map((i) => i.text);
  for (const item of group.items) {
    bank.push({
      text: item.text,
      meaning: item.meaning,
      example: item.example || "",
      cluster: group.cluster,
    });
    const others = texts.filter((t) => t !== item.text);
    similar[item.text] = others.slice(0, 4);
    byCluster[item.text] = group.cluster;
  }
}

bank.sort((a, b) => a.text.localeCompare(b.text, "zh-CN"));

const bankJs =
  "/* eslint-disable */\n" +
  "/** Built-in idiom bank — generated by tools/build-bank.js */\n" +
  "window.CHENGYU_BANK = " +
  JSON.stringify(bank, null, 2) +
  ";\n";

const similarJs =
  "/* eslint-disable */\n" +
  "/** Precomputed similar idioms (2–4 each) — generated by tools/build-bank.js */\n" +
  "window.CHENGYU_SIMILAR = " +
  JSON.stringify(similar, null, 2) +
  ";\n";

const clusterJs =
  "/* eslint-disable */\n" +
  "window.CHENGYU_CLUSTER_BY_TEXT = " +
  JSON.stringify(byCluster, null, 2) +
  ";\n";

fs.writeFileSync(path.join(root, "chengyu-bank.js"), bankJs);
fs.writeFileSync(path.join(root, "chengyu-similar.js"), similarJs);
fs.writeFileSync(path.join(root, "chengyu-clusters-map.js"), clusterJs);

console.log(`Wrote ${bank.length} idioms to chengyu-bank.js`);